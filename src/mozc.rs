//! A persistent Mozc helper, using bounded nonblocking stdin/stdout pipes.
//! No shell, HTTP server, or extra runtime is involved.
use crate::{
    converter::{Candidate, Conversion, Segment},
    text,
};
use std::{
    fs,
    io::{self, Read, Write},
    os::{fd::AsRawFd, unix::fs::PermissionsExt},
    process::{Child, Command, Stdio},
    time::{Duration, Instant},
};

pub struct Mozc {
    helper: String,
    profile: String,
    child: Option<Child>,
    buffer: Vec<u8>,
    failed: bool,
    pub error: String,
}

fn nonblocking(fd: i32) -> io::Result<()> {
    // SAFETY: fd is borrowed from a live ChildStdin/ChildStdout for this call.
    unsafe {
        let flags = libc::fcntl(fd, libc::F_GETFL);
        if flags < 0 || libc::fcntl(fd, libc::F_SETFL, flags | libc::O_NONBLOCK) < 0 {
            return Err(io::Error::last_os_error());
        }
    }
    Ok(())
}
fn wait(fd: i32, event: i16, deadline: Instant) -> io::Result<()> {
    loop {
        let ms = deadline
            .saturating_duration_since(Instant::now())
            .as_millis()
            .clamp(1, i32::MAX as u128) as i32;
        if Instant::now() >= deadline {
            return Err(io::ErrorKind::TimedOut.into());
        }
        let mut descriptor = libc::pollfd {
            fd,
            events: event,
            revents: 0,
        };
        // SAFETY: poll receives one initialized descriptor with a valid lifetime.
        let result = unsafe { libc::poll(&mut descriptor, 1, ms) };
        if result > 0 {
            if descriptor.revents & event != 0 {
                return Ok(());
            }
            return Err(io::ErrorKind::BrokenPipe.into());
        }
        if result == 0 {
            return Err(io::ErrorKind::TimedOut.into());
        }
        let error = io::Error::last_os_error();
        if error.kind() != io::ErrorKind::Interrupted {
            return Err(error);
        }
    }
}
fn write_pipe(pipe: &mut impl Write, bytes: &[u8]) -> io::Result<usize> {
    // SAFETY: signal masks are local to this thread. Restore the old mask even
    // when the peer has exited; consume only the SIGPIPE generated by this write.
    unsafe {
        let mut blocked: libc::sigset_t = std::mem::zeroed();
        let mut old = std::mem::zeroed();
        let mut pending = std::mem::zeroed();
        libc::sigemptyset(&mut blocked);
        libc::sigaddset(&mut blocked, libc::SIGPIPE);
        let status = libc::pthread_sigmask(libc::SIG_BLOCK, &blocked, &mut old);
        if status != 0 {
            return Err(io::Error::from_raw_os_error(status));
        }
        libc::sigpending(&mut pending);
        let result = pipe.write(bytes);
        if result
            .as_ref()
            .is_err_and(|e| e.kind() == io::ErrorKind::BrokenPipe)
            && libc::sigismember(&pending, libc::SIGPIPE) == 0
            && libc::sigismember(&old, libc::SIGPIPE) == 0
        {
            let zero = libc::timespec {
                tv_sec: 0,
                tv_nsec: 0,
            };
            libc::sigtimedwait(&blocked, std::ptr::null_mut(), &zero);
        }
        libc::pthread_sigmask(libc::SIG_SETMASK, &old, std::ptr::null_mut());
        result
    }
}
fn safe(value: &str) -> bool {
    value.bytes().all(|c| c >= 0x20)
}
fn ascii(value: &str) -> String {
    value.chars().filter(char::is_ascii).collect()
}

impl Mozc {
    pub fn new(helper: String, profile: String) -> Self {
        Self {
            helper,
            profile,
            child: None,
            buffer: Vec::new(),
            failed: false,
            error: String::new(),
        }
    }
    fn stop(&mut self) {
        if let Some(mut child) = self.child.take() {
            let _ = child.kill();
            let _ = child.wait();
        }
        self.buffer.clear();
    }
    fn receive(&mut self, deadline: Instant) -> io::Result<String> {
        loop {
            if let Some(end) = self.buffer.iter().position(|&c| c == b'\n') {
                if end > 1024 * 1024 {
                    return Err(io::ErrorKind::InvalidData.into());
                }
                let value = String::from_utf8(self.buffer[..end].to_vec())
                    .map_err(|_| io::ErrorKind::InvalidData)?;
                self.buffer.drain(..=end);
                return Ok(value);
            }
            if self.buffer.len() > 1024 * 1024 {
                return Err(io::ErrorKind::InvalidData.into());
            }
            let pipe = self.child.as_mut().unwrap().stdout.as_mut().unwrap();
            wait(pipe.as_raw_fd(), libc::POLLIN, deadline)?;
            let mut bytes = [0; 8192];
            match pipe.read(&mut bytes) {
                Ok(0) => return Err(io::ErrorKind::UnexpectedEof.into()),
                Ok(n) => self.buffer.extend_from_slice(&bytes[..n]),
                Err(e)
                    if matches!(
                        e.kind(),
                        io::ErrorKind::WouldBlock | io::ErrorKind::Interrupted
                    ) => {}
                Err(e) => return Err(e),
            }
        }
    }
    fn start(&mut self) -> io::Result<()> {
        if self.child.is_some() {
            return Ok(());
        }
        if self.failed || self.helper.is_empty() {
            return Err(io::Error::other("Mozc helper unavailable"));
        }
        fs::create_dir_all(&self.profile)?;
        fs::set_permissions(&self.profile, fs::Permissions::from_mode(0o700))?;
        let child = Command::new(&self.helper)
            .arg(&self.profile)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .spawn()?;
        self.child = Some(child);
        let child = self.child.as_ref().unwrap();
        nonblocking(child.stdin.as_ref().unwrap().as_raw_fd())?;
        nonblocking(child.stdout.as_ref().unwrap().as_raw_fd())?;
        if self.receive(Instant::now() + Duration::from_millis(1500))? != "READY" {
            return Err(io::Error::other("invalid Mozc greeting"));
        }
        Ok(())
    }
    fn exchange(&mut self, reading: &str, context: &str) -> io::Result<String> {
        self.start()?;
        let request = format!("C\t{}\t{reading}\n", text::suffix(context, 64));
        let deadline = Instant::now() + Duration::from_millis(300);
        let pipe = self.child.as_mut().unwrap().stdin.as_mut().unwrap();
        let mut bytes = request.as_bytes();
        while !bytes.is_empty() {
            wait(pipe.as_raw_fd(), libc::POLLOUT, deadline)?;
            match write_pipe(pipe, bytes) {
                Ok(0) => return Err(io::ErrorKind::WriteZero.into()),
                Ok(n) => bytes = &bytes[n..],
                Err(e)
                    if matches!(
                        e.kind(),
                        io::ErrorKind::WouldBlock | io::ErrorKind::Interrupted
                    ) => {}
                Err(e) => return Err(e),
            }
        }
        self.receive(deadline)
    }
    pub fn convert(
        &mut self,
        reading: &str,
        context: &str,
        cancelled: &dyn Fn() -> bool,
    ) -> Option<Conversion> {
        if cancelled()
            || reading.is_empty()
            || reading.len() > 1024
            || reading.chars().count() > 256
            || !safe(reading)
            || !safe(context)
        {
            return None;
        }
        if !reading.chars().any(text::is_kana) {
            self.error.clear();
            return Some(Conversion::literal(reading));
        }
        let reply = match self.exchange(reading, context) {
            Ok(reply) => reply,
            Err(error) => {
                self.error = format!("Mozc: {error}");
                self.failed = true;
                self.stop();
                return None;
            }
        };
        // A cancelled response is still drained to keep the next query aligned.
        if cancelled() {
            return None;
        }
        let result = parse(reading, &reply);
        self.error = if result.is_some() {
            String::new()
        } else {
            "invalid Mozc response".into()
        };
        result
    }
}
impl Drop for Mozc {
    fn drop(&mut self) {
        self.stop();
    }
}

pub fn parse(reading: &str, reply: &str) -> Option<Conversion> {
    if reply.is_empty() || reply.len() > 1024 * 1024 || reading.len() > 1024 || !safe(reading) {
        return None;
    }
    let mut out = Conversion {
        reading: reading.into(),
        ..Conversion::default()
    };
    let mut reconstructed = String::new();
    let mut candidate_bytes = 0;
    for record in reply.split('\x1e').take(257) {
        let mut fields = record.split('\x1f');
        let key = fields.next()?;
        if key.is_empty() || !safe(key) {
            return None;
        }
        let mut segment = Segment {
            reading: key.into(),
            literal: !key.chars().any(text::is_kana),
            ..Segment::default()
        };
        let signature = ascii(key);
        let mut found_separator = false;
        for value in fields.take(256) {
            found_separator = true;
            if !safe(value) {
                return None;
            }
            if !value.is_empty()
                && value.len() <= 1024
                && candidate_bytes + value.len() <= 65536
                && ascii(value) == signature
                && segment.candidates.len() < 9
                && !segment.candidates.iter().any(|c| c.text == value)
            {
                candidate_bytes += value.len();
                segment
                    .candidates
                    .push(Candidate::new(value, -(segment.candidates.len() as f64)));
            }
        }
        if !found_separator {
            return None;
        }
        if segment.candidates.is_empty() {
            segment.candidates.push(Candidate::new(key, 0.0));
        }
        reconstructed.push_str(key);
        out.segments.push(segment);
        if out.segments.len() > 256 {
            return None;
        }
    }
    if reconstructed != reading {
        return None;
    }
    out.rebuild_candidates(9);
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn protocol_preserves_literals() {
        let result = parse(
            "CPUしようりつは12.5%",
            "CPU\x1fＣＰＵ\x1fCPU\x1eしようりつは\x1f使用率は\x1e12.5%\x1f１２．５％\x1f12.5%",
        )
        .unwrap();
        assert_eq!(result.text(), "CPU使用率は12.5%");
        assert!(parse("かな", "べつ\x1f別").is_none());
        assert!(parse("かな", "かな\x1f仮\n名").is_none());
        assert!(parse("かな", "かな").is_none());
    }
}
